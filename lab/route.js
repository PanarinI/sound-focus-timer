// route.js — МАРШРУТ В СЦЕНЕ. Один источник для двух поверхностей, как у `icon.js`:
// подключается и в панель (`hearth.html` → SKY), и в стенд (`lab/route-stand.html`),
// чтобы автор выбирал вкус ровно на том, что уедет в продукт.
// Никаких chrome- и DOM-зависимостей: только 2d-контекст, переданный снаружи.
//
// ЗАКОН (тот же, что у иконки): показываем ОСТАВШИЙСЯ ПУТЬ, а не утекающее время.
// Без цифр, без красного, без ускорения к финалу — «сопровождает, не наказывает».
//
// ГЕОМЕТРИЯ. Наблюдатель летит В точку схода (звезда-цель, cx/cy). Веха НЕ на самой оси —
// там она схлопнулась бы в точку; у неё боковой вынос, и экранный радиус живёт по перспективе
// r = K / глубина. Дальние вехи жмутся к звезде, ближняя проносится мимо и уходит за кромку.
// Это ровно та перспектива, по которой уже живёт звёздное поле: маршрут не нарисован ПОВЕРХ
// сцены — он в ней. Остаток читается как РАССТОЯНИЕ (сколько огней ещё между тобой и звездой),
// пройденное — как «пронеслось позади». Считать не обязательно: глаз ловит, что впереди редеет.
//
// МЕРА ПУТИ. Вех всегда N на весь рейс, независимо от длины (как дуга иконки — доля, не минуты):
// одна веха = десятая часть пути и в пятиминутном рейсе, и в девяностоминутном.
(() => {
  'use strict';

  const WARM = '232,178,92';     // тёплый янтарь — палитра рейса (общая с иконкой)
  const N = 10;                  // вех на весь маршрут: одна = десятая доля пути
  const K = 12;                  // перспектива: радиус вехи = K / глубина (px при глубине 1)
  const PHI = 2.399963;          // золотое вращение — углы вех не выстраиваются в решётку
  const TURN = 0.62;             // шаг закрутки спирали (вариант 2): путь читается как единый ход, а не россыпь

  // предвычисленные вехи: доля пути + собственный угол выноса
  const MARKS = Array.from({ length: N }, (_, i) => ({
    u: (i + 0.5) / N,
    ang: i * PHI,
    spi: i * TURN,               // угол для спирального коридора
  }));

  // мягкая ступень (без резких границ — закон капсулы 07-04)
  const smooth = (e0, e1, x) => {
    const t = Math.max(0, Math.min(1, (x - e0) / (e1 - e0)));
    return t * t * (3 - 2 * t);
  };

  // Веха должна читаться КАК ВЕХА, а не как звезда поля. Различают две вещи, обе тихие:
  // ореол (у звёзд его нет — они точки) и РОВНЫЙ свет (звёзды дышат, веха стоит).
  // Ни размером, ни цветом не кричим — иначе это уже интерфейс поверх сцены.
  function dot(ctx, px, py, size, a) {
    ctx.fillStyle = `rgb(${WARM})`;
    ctx.globalAlpha = a * 0.20;
    ctx.beginPath(); ctx.arc(px, py, size * 2.7, 0, 6.283); ctx.fill();
    ctx.globalAlpha = a;
    ctx.beginPath(); ctx.arc(px, py, size, 0, 6.283); ctx.fill();
  }

  // s = { W, H, cx, cy, prog, alpha, t, variant }
  function drawRoute(ctx, s) {
    const { W, H, cx, cy } = s;
    const prog = Math.max(0, Math.min(1, s.prog || 0));
    const A = Math.max(0, Math.min(1, s.alpha == null ? 1 : s.alpha));
    if (A < 0.002 || !W || !H) return;
    const variant = s.variant || 1;
    const maxR = Math.hypot(Math.max(cx, W - cx), Math.max(cy, H - cy));
    const t = s.t || 0;

    const prev = ctx.globalCompositeOperation;
    ctx.globalCompositeOperation = 'lighter';       // тёплое сложение, как у звёздного поля

    for (const m of MARKS) {
      const depth = m.u - prog;
      if (depth <= 0.004) continue;                 // веха уже позади — не тянем её обратно в кадр
      const r = K / depth;
      if (r > maxR * 1.25) continue;                // ещё/уже за кромкой

      // проявление у звезды и уход за кромкой — оба мягкие, вспышек нет
      const born = smooth(K * 0.9, K * 2.2, r);
      const gone = 1 - smooth(maxR * 0.62, maxR * 1.15, r);
      const a = A * born * gone * 0.85;
      if (a < 0.004) continue;

      const size = Math.min(3.2, 1.1 + r * 0.014);

      if (variant === 3) {
        // 3 — ПЫЛЕВАЯ ДОРОЖКА: не огни, а сгусток пыли на месте вехи. Считать нечего,
        // остаток читается плотностью: чем ближе к прибытию, тем чище воздух впереди.
        for (let k = 0; k < 5; k++) {
          const rr = r * (0.82 + 0.36 * ((k * 0.37) % 1));
          const aa = m.ang + k * 1.7 + Math.sin(t * 0.12 + k) * 0.22;
          dot(ctx, cx + Math.cos(aa) * rr, cy + Math.sin(aa) * rr, size * 0.6, a * 0.5);
        }
      } else if (variant === 2) {
        // 2 — СПИРАЛЬНЫЙ КОРИДОР: углы вех идут ровным шагом, и цепочка огней закручивается
        // к звезде. Глаз ведёт по ней как по одному ходу — путь, а не россыпь. Каждая веха
        // одиночная: спираль сама держит форму, второй огонь ей не нужен.
        dot(ctx, cx + Math.cos(m.spi) * r, cy + Math.sin(m.spi) * r, size, a);
      } else {
        // 1 — ВОРОТА (по умолчанию): веха = пара огней по обе стороны курса.
        // Симметрия делает её вехой, а не случайной звездой: сквозь створ пролетаешь.
        const dx = Math.cos(m.ang), dy = Math.sin(m.ang);
        dot(ctx, cx + dx * r, cy + dy * r, size, a);
        dot(ctx, cx - dx * r, cy - dy * r, size, a);
      }
    }

    ctx.globalAlpha = 1;
    ctx.globalCompositeOperation = prev;
  }

  globalThis.drawRoute = drawRoute;
  globalThis.ROUTE_MARKS = N;
})();
